// POST /.netlify/functions/thank-you-post — приймає повернення з WayForPay.
//
// WayForPay віддає Return URL не звичайним переходом за посиланням, а
// HTTP POST-запитом із даними транзакції у тілі. Статичний хостинг Netlify
// не вміє відповідати на POST до звичайного .html-файлу (віддає 404) —
// саме тому пряме посилання на thank-you.html у полі Return URL ламалось
// (біла сторінка / помилка браузера) і на телефоні, і в комп'ютерному
// браузері.
//
// Ця функція приймає будь-який метод (Functions на це здатні, на відміну
// від статичних файлів) і одразу віддає 303-редірект на справжню сторінку —
// браузер сам перезапитує її вже звичайним GET, який працює без проблем.
// Тіло POST (дані транзакції від WayForPay) свідомо ігнорується: для
// показу сторінки й трекінгу Purchase воно не потрібне.

exports.handler = async () => {
  return {
    statusCode: 303,
    headers: { Location: '/thank-you.html?fbpurchase=1' },
  };
};
